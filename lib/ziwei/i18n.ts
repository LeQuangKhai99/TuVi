export function tStar(name: string): string {
  return STAR_VI_MAP[name] || name;
}

export function tPalace(name: string): string {
  return PALACE_VI_MAP[name] || name;
}

export function tStem(stem: number | string): string {
  if (typeof stem === 'number') return STEM_VI[stem] ?? String(stem);
  const idx = STEM_ZH.indexOf(stem);
  return idx >= 0 ? STEM_VI[idx] : stem;
}

export function tBranch(branch: number | string): string {
  if (typeof branch === 'number') return BRANCH_VI[branch] ?? String(branch);
  const idx = BRANCH_ZH.indexOf(branch);
  return idx >= 0 ? BRANCH_VI[idx] : branch;
}

export function tGanzhi(stem: number | string, branch: number | string): string {
  return `${tStem(stem)} ${tBranch(branch)}`;
}

export function tJu(juName: string): string {
  return JU_VI_MAP[juName] || juName;
}

export function tSiHua(siHua: string): string {
  return SIHUA_VI_MAP[siHua] || siHua;
}

export function tBrightness(b: string): string {
  return BRIGHTNESS_VI_MAP[b] || b;
}

export function tPattern(name: string): string {
  return PATTERN_VI_MAP[name] || name;
}
